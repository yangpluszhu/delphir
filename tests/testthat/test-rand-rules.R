test_that("RAND questionnaires write docx and xlsx that can be read back", {
  ram <- simulate_ram_classic()
  d <- tempfile("ramq-")
  dir.create(d)
  paths <- rand_questionnaire(ram, round = 1, format = "both", file = d, prefill = TRUE)
  expect_true(any(grepl("\\.docx$", paths)))
  expect_true(any(grepl("\\.xlsx$", paths)))
  expect_true(all(file.exists(paths)))
  xlsx <- paths[grepl("\\.xlsx$", paths)][1]
  got <- read_survey_xlsx(xlsx)
  expect_equal(sort(unique(got$ratings$dimension)), "适宜性")
  expect_true(any(!is.na(got$ratings$score)))

  r2 <- rand_questionnaire(ram, round = 2, format = "xlsx", file = tempfile(fileext = ".xlsx"))
  raw <- openxlsx::read.xlsx(r2, sheet = "\u8bc4\u5206")
  expect_equal(length(unique(raw$item_id)), nrow(ram$items))
  expect_true("own_prev" %in% names(raw))

  nec <- simulate_rand_necessity()
  npath <- rand_questionnaire(nec, round = "necessity", format = "xlsx",
                              file = tempfile(fileext = ".xlsx"))
  nraw <- openxlsx::read.xlsx(npath, sheet = "\u8bc4\u5206")
  expect_equal(unique(as.character(nraw$dimension)), "\u5fc5\u8981\u6027")
  expect_true(all(nraw$item_id %in% c("IND01", "IND05", "IND07")))
  expect_equal(length(unique(nraw$item_id)), 3L)
})

