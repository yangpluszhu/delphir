test_that("manual examples separate table 4 from IPRAS", {
  polar <- rand_disagreement(c(1, 2, 2, 3, 5, 7, 8, 9, 9), method = "both")
  expect_equal(polar$median, 5)
  expect_equal(polar$n_low, 4)
  expect_equal(polar$n_high, 4)
  expect_true(polar$table4_disagreement)
  expect_true(polar$ipras_disagreement)
  expect_equal(polar$p30, 2.4, tolerance = 1e-8)
  expect_equal(polar$p70, 7.6, tolerance = 1e-8)
  expect_equal(polar$class, "uncertain")
  expect_equal(polar$class_detail, "uncertain_disagreement")

  agree <- rand_disagreement(c(6, 7, 7, 8, 8, 8, 9, 9, 9), method = "table4")
  expect_equal(agree$median, 8)
  expect_false(agree$table4_disagreement)
  expect_false(agree$ipras_disagreement)
  expect_equal(agree$n_out, 1)
  expect_equal(agree$agreement_status, "agreement")
  expect_equal(agree$class, "appropriate")
  expect_equal(agree$p30, 7.4, tolerance = 1e-8)
  expect_equal(agree$p70, 8.6, tolerance = 1e-8)

  split_rule <- rand_disagreement(c(2, 3, 3, 7, 8, 8, 8, 9, 9), method = "table4")
  expect_true(split_rule$table4_disagreement)
  expect_false(split_rule$ipras_disagreement)
  expect_equal(split_rule$p30, 4.6, tolerance = 1e-8)
  expect_equal(split_rule$p70, 8, tolerance = 1e-8)
  expect_equal(split_rule$ipr, 3.4, tolerance = 1e-8)
  expect_equal(split_rule$class_detail, "uncertain_disagreement")
  ipras_only <- rand_disagreement(c(2, 3, 3, 7, 8, 8, 8, 9, 9), method = "ipras")
  expect_false(ipras_only$disagreement)
  expect_equal(ipras_only$class, "appropriate")
})

